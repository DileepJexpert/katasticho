	nd.pack_size, nd.mrp::numeric, nd.prescription_required::boolean, true
FROM new_drugs nd
LEFT JOIN public.salt_master sm ON lower(sm.name) = lower(nd.generic_name)
WHERE NOT EXISTS (
	SELECT 1 FROM public.drug_master d
	WHERE lower(d.brand_name) = lower(nd.brand_name))
ORDER BY lower(nd.brand_name);
