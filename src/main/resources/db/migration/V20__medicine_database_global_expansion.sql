-- V20: Global medicine database expansion.
--
-- Grows the platform reference masters (salt_master / manufacturer_master /
-- drug_master) beyond the India-centric V2 seed, curated from public retail
-- catalogues the trade actually uses:
--   * Indian retail lists (Marg-style distributor lists, 1mg / Apollo
--     bestsellers, 2024-25 launches such as Wegovy / Mounjaro / Vymada),
--   * Jan Aushadhi (PMBI) and DavaIndia (Zota Healthcare) generic ranges,
--   * Gulf / GCC retail brands (UAE, Saudi, Oman) for the AE/OM expansion,
--   * East & South Africa staples (Kenya focus) for the KE expansion,
--   * Global US/EU brands for cross-border reference completeness.
--
-- Conventions:
--   * salt_master / manufacturer_master: ON CONFLICT (name) DO NOTHING —
--     both tables carry UNIQUE(name), so re-runs and V2 overlaps are no-ops.
--   * drug_master has NO unique key on brand_name, so every batch inserts
--     through a VALUES CTE guarded by a case-insensitive NOT EXISTS on
--     brand_name plus DISTINCT ON to collapse intra-batch duplicates.
--     Brands already present from the V2 seed are silently skipped.
--   * salt_id resolves by case-insensitive name match on salt_master
--     (same shape as the V2 rows); combos that have no salt row keep a
--     NULL salt_id with the full salt_composition text.
--   * MRP is the approximate local retail price for Indian rows (INR) and
--     NULL for non-Indian market rows — orgs set their own price when they
--     add the item (PosCatalogService passes MRP straight into salePrice,
--     and a NULL there is safer than a fabricated cross-currency number).
--   * drug_schedule uses the Indian buckets that drive the POS prescription
--     dialog + statutory registers: GENERAL / H / H1 / X. Foreign Rx brands
--     carry H (or H1/X where the molecule is on the Indian H1/X lists, e.g.
--     cefixime, azithromycin, alprazolam, zolpidem → H1; methylphenidate → X)
--     so prescription_required behaves for any org that stocks them.
--   * GST/HSN per post-GST-2.0 rates: 3004 medicines 5%, 9018/9019 devices
--     5%, 3822 test strips/kits 5%, 3005 dressings 5%, 1901 infant/malt
--     foods 5%, 1702 glucose 5%, 4014 condoms 0%, 2106 supplements 18%,
--     3304 dermo-cosmetics 18%, 3808 antiseptic liquids 18%, 9025
--     thermometers 18%.

